using System.Net;
using System.Net.Http.Json;
using FluentAssertions;
using Microsoft.Extensions.DependencyInjection;
using Volterp.Application.DTOs;
using Volterp.Infrastructure.Data;
using Volterp.Tests.Onboarding;
using Xunit;

namespace Volterp.Tests.Integration;

// The model does not seed any company nor any administrator anymore, so the
// test brings its own tenant: the command of the deployment creates the
// company with its RNC and its administrator with the password it shows.
[Collection("VolterpApiFactory")]
public class LoginAuthenticationTests : IClassFixture<LoginFixture>
{
    private readonly LoginFixture _fixture;

    public LoginAuthenticationTests(LoginFixture fixture) => _fixture = fixture;

    [Fact]
    public async Task Login_WithValidCredentials_ReturnsToken()
    {
        var response = await _fixture.Client.PostAsJsonAsync("/api/auth/login",
            new { username = _fixture.AdminUsername, password = _fixture.AdminPassword });

        response.StatusCode.Should().Be(HttpStatusCode.OK,
            "the credential lookup must not be tenant-scoped: before authenticating there is no company claim, so the tenant filter hides every row and login can never succeed.");

        var body = await response.Content.ReadFromJsonAsync<LoginResponse>();

        body.Should().NotBeNull();
        body!.Token.Should().NotBeNullOrEmpty();
        body.Username.Should().Be(_fixture.AdminUsername);
        body.CompanyId.Should().Be(_fixture.CompanyId);
    }

    [Fact]
    public async Task Login_WithWrongPassword_ReturnsUnauthorized()
    {
        var response = await _fixture.Client.PostAsJsonAsync("/api/auth/login",
            new { username = _fixture.AdminUsername, password = "not-the-password" });

        response.StatusCode.Should().Be(HttpStatusCode.Unauthorized,
            "bypassing the tenant filter must not weaken the password check.");
    }
}

// The tenant of the login test: a company with a real RNC and an administrator
// whose password was generated by the command of the deployment.
public class LoginFixture : IAsyncLifetime
{
    private readonly ApiFactory _factory = new();

    public HttpClient Client { get; private set; } = null!;
    public string AdminUsername { get; private set; } = null!;
    public string AdminPassword { get; private set; } = null!;
    public Guid CompanyId { get; private set; }

    public async Task InitializeAsync()
    {
        Client = _factory.CreateClient();
        _factory.EnsureSchemaCreated();

        using var scope = _factory.Services.CreateScope();
        var context = scope.ServiceProvider.GetRequiredService<VolterpDbContext>();

        var outcome = await TenantSeeder.SeedAsync(context);

        AdminUsername = outcome.AdminUsername;
        AdminPassword = outcome.AdminPassword!;
        CompanyId = outcome.CompanyId;
    }

    public Task DisposeAsync()
    {
        Client.Dispose();
        _factory.Dispose();

        return Task.CompletedTask;
    }
}
